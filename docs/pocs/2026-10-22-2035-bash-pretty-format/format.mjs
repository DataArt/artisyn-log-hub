// Renders samples.json through bash-view.mjs into a markdown page of before/after examples.
//   node format.mjs [out.md]      (default: examples.md next to this script)
// Nothing is executed — commands are only parsed.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { init, parse, format, analyze, liftCd } from './bash-view.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const HEREDOC_INLINE_MAX = 8

await init()

/** Short lists inline; longer ones grouped by directory, one line per directory. */
function fileList(files) {
  if (files.length <= 3) return files.map((f) => `\`${f}\``).join(', ')
  const groups = new Map()
  for (const p of files) {
    const i = p.lastIndexOf('/')
    const dir = i < 0 ? './' : p.slice(0, i + 1)
    if (!groups.has(dir)) groups.set(dir, [])
    groups.get(dir).push(p.slice(i + 1))
  }
  return '\n' + [...groups].map(([d, names]) => `  - \`${d}\` ${names.map((n) => `\`${n}\``).join(', ')}`).join('\n')
}

/** Heredoc bodies (from the syntax tree) longer than N lines are folded out of the script. */
function foldHeredocs(src, script) {
  const bodies = parse(src).rootNode.descendantsOfType('heredoc_body')
  const folded = []
  let out = script
  for (const b of bodies) {
    const lines = b.text.replace(/\n$/, '').split('\n')
    if (lines.length <= HEREDOC_INLINE_MAX || !out.includes(b.text)) continue
    const stmt = b.parent.parent
    const n = folded.length + 1
    folded.push({ n, head: stmt.text.split('\n')[0], body: lines.join('\n') })
    out = out.replace(b.text, `# ▼ block ${n}: ${lines.length} lines, shown below\n`)
  }
  return { script: out, folded }
}

function render({ id, command }) {
  const parts = [`## ${id}`, '', `**Before** — raw, ${command.length} chars, ${command.split('\n').length} line(s):`, '', '```text', command.length > 700 ? command.slice(0, 700) + ' …[cut]' : command, '```', '']
  const f = format(command)
  if (!f.ok) {
    parts.push('**After** — not parseable as bash: shown as is.', '')
    return parts.join('\n')
  }
  const a = analyze(command)
  const lifted = liftCd(command, f.script)
  const { script, folded } = foldHeredocs(command, lifted.script)
  parts.push('**After:**', '')
  if (lifted.dir) parts.push(`📂 \`${lifted.dir}\``, '')
  if (a.written.length) parts.push(`✏️ **Changes** — ${fileList(a.written)}`, '')
  if (a.read.length) parts.push(`👁 **Reads** — ${fileList(a.read)}`, '')
  if (a.runs.length) parts.push(`▶ **Runs** — ${a.runs.map((r) => `\`${r}\``).join(', ')}`, '')
  for (const s of a.scripts) parts.push(`📜 inline \`${s.command}\` script, ${s.lines} lines — files it touches are not analysed`, '')
  parts.push('```bash', script, '```', '')
  for (const b of folded) {
    parts.push(`<details><summary>block ${b.n} — <code>${b.head.replace(/&/g, '&amp;').replace(/</g, '&lt;')}</code></summary>`, '', '```text', b.body, '```', '', '</details>', '')
  }
  return parts.join('\n')
}

const samples = JSON.parse(readFileSync(join(here, 'samples.json'), 'utf8'))
const outFile = process.argv[2] ?? join(here, 'examples.md')
const head = [
  '# Bash command pretty-format — PoC examples',
  '',
  'Generated by `node format.mjs` in `docs/pocs/2026-10-22-2035-bash-pretty-format/` from its',
  "`samples.json` (10 real Bash tool calls of one Claude Code session). See that folder's README.",
  'Everything below is derived from the bash syntax tree only; nothing was executed.',
  '',
]
writeFileSync(outFile, head.concat(samples.map(render)).join('\n'))
console.log(`wrote ${outFile}`)
